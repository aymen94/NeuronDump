//! Ollama Modelfile text, validation of the written file and the llama-perplexity comparison.

use super::*;

pub fn modelfile_text(m: &ModelHandle, gguf_name: &str, include_projector: bool) -> String {
    modelfile_text_with(m, gguf_name, include_projector, true)
}

pub fn modelfile_text_with(m: &ModelHandle, gguf_name: &str, include_projector: bool, include_template: bool) -> String {
    let mut s = format!("# Generated by NeuronDump from {}\nFROM ./{gguf_name}\n", m.entry.name);
    if include_projector {
        if let Some(p) = &m.entry.projector {
            s.push_str(&format!("FROM {}\n", p.display()));
        }
    }
    if let Some(t) = m.ollama.template.as_ref().filter(|_| include_template) {
        s.push_str(&format!("TEMPLATE \"\"\"{t}\"\"\"\n"));
    }
    if let Some(sys) = &m.ollama.system {
        s.push_str(&format!("SYSTEM \"\"\"{sys}\"\"\"\n"));
    }
    if let Some(serde_json::Value::Object(params)) = &m.ollama.params {
        for (k, v) in params {
            let vals: Vec<&serde_json::Value> = match v {
                serde_json::Value::Array(a) => a.iter().collect(),
                v => vec![v],
            };
            for v in vals {
                match v {
                    serde_json::Value::String(x) => s.push_str(&format!("PARAMETER {k} {}\n", serde_json::to_string(x).unwrap_or_default())),
                    other => s.push_str(&format!("PARAMETER {k} {other}\n")),
                }
            }
        }
    }
    for lic in &m.ollama.licenses {
        s.push_str(&format!("LICENSE \"\"\"{lic}\"\"\"\n"));
    }
    s
}

pub fn validate(path: &Path) -> Validation {
    let mut problems = Vec::new();
    let g = match GgufFile::open(path) {
        Ok(g) => g,
        Err(e) => {
            return Validation { ok: false, n_tensors: 0, n_vocab: None, block_count: None, problems: vec![format!("re-parse failed: {e}")] }
        }
    };
    for w in &g.warnings {
        problems.push(w.clone());
    }
    for t in &g.tensors {
        if g.info_bytes(t).is_err() {
            problems.push(format!("tensor {} out of bounds", t.name));
        }
    }
    let n_vocab = g.get("tokenizer.ggml.tokens").and_then(|v| v.as_array()).map(|a| a.len());
    if let (Some(n), Some(t)) = (n_vocab, g.tensor("token_embd.weight")) {
        if t.n_rows() != n {
            problems.push(format!("token_embd has {} rows but vocabulary has {n} tokens", t.n_rows()));
        }
    }
    for k in crate::tokenizer::special_token_keys(&g) {
        if let (Some(id), Some(n)) = (g.get_u64(&k), n_vocab) {
            if id >= n {
                problems.push(format!("{k} = {id} is outside the vocabulary ({n})"));
            }
        }
    }
    let block_count = g.arch_key("block_count").and_then(|v| v.as_u64());
    let layers: BTreeSet<u32> = g.tensors.iter().filter_map(|t| parse_tensor_name(&t.name).layer).collect();
    if let Some(bc) = block_count {
        if !layers.is_empty() && bc as usize != layers.len() {
            problems.push(format!("block_count {bc} but {} layers have tensors", layers.len()));
        }
        if layers.iter().next_back().is_some_and(|&l| l as u64 + 1 != bc) {
            problems.push("layer indices are not contiguous".into());
        }
    }
    Validation { ok: problems.is_empty(), n_tensors: g.tensors.len(), n_vocab, block_count, problems }
}

pub(super) fn find_tool(name: &str) -> Option<PathBuf> {
    let exe = if cfg!(windows) { format!("{name}.exe") } else { name.to_string() };
    std::env::var_os("PATH").and_then(|paths| std::env::split_paths(&paths).map(|d| d.join(&exe)).find(|p| p.is_file()))
}

pub(super) fn run_perplexity(tool: &Path, model: &Path, corpus: &Path, ctx: usize) -> (Option<f64>, String) {
    let out = Command::new(tool)
        .arg("-m")
        .arg(model)
        .arg("-f")
        .arg(corpus)
        .args(["-c", &ctx.to_string(), "--chunks", "8"])
        .output();
    match out {
        Ok(o) => {
            let text = format!("{}{}", String::from_utf8_lossy(&o.stdout), String::from_utf8_lossy(&o.stderr));
            let ppl = text
                .lines()
                .find_map(|l| l.split("Final estimate: PPL = ").nth(1))
                .and_then(|r| r.split_whitespace().next())
                .and_then(|v| v.parse().ok());
            let tail: String = text.lines().rev().take(6).collect::<Vec<_>>().into_iter().rev().collect::<Vec<_>>().join("\n");
            (ppl, tail)
        }
        Err(e) => (None, format!("failed to run {}: {e}", tool.display())),
    }
}
